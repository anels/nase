#!/usr/bin/env python3
"""Sync workspace skills into model-invocable command stubs.

`workspace/skills/*.md` is the source of truth. Each skill becomes a thin
command wrapper at `.claude/commands/nase/workspace/<name>.md` that carries the
skill's frontmatter and points back at the source file.

This used to run as a Bash loop inside the SessionStart hook. That version
spent about 1.2 seconds of a 1.5 second session start on process spawns alone:
nine `awk` calls per skill, plus a temp file, a comparison and a rename for
every skill on every session. One Python pass does the same work in a few
milliseconds.

Two behaviors are load-bearing and must not change:

* A stub is rewritten when its bytes differ from the generated bytes, never
  when its mtime differs. A stale stub with a newer timestamp still has to be
  regenerated, or a long description stays loaded into slash-command metadata
  and keeps costing context in every later session.
* A stub whose content already matches is left in place and only has its file
  mode repaired.

Exit codes: 0 nothing changed, 10 something changed (the caller reloads
skills), 1 the sync failed.
"""

from __future__ import annotations

import argparse
import contextlib
import os
import pathlib
import re
import shutil
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from nase_fs import atomic_write

# A stub name has to be a safe command name: lowercase, digits and dashes.
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
# A frontmatter key line, used to find the end of a captured block.
KEY_RE = re.compile(r"^[A-Za-z0-9_-]+:")
# A YAML block scalar header, e.g. `description: |`.
BLOCK_SCALAR_RE = re.compile(r"^[|>][+-]?$")

# Frontmatter keys the wrapper forwards, in the order the wrapper prints them.
FORWARDED_KEYS = (
    "argument-hint",
    "when_to_use",
    "model",
    "effort",
    "context",
    "agent",
    "allowed-tools",
    "disallowed-tools",
)
# The key that marks a skill as user-invoked only.
INVOCATION_KEY = "disable-model-invocation"

MAX_DESCRIPTION = 240
STUB_MODE = 0o644
NATIVE_MARKER = "<!-- NASE-GENERATED-WORKSPACE-SKILL"


def split_frontmatter(lines: list[str]) -> tuple[list[str], list[str]]:
    """Split a skill into (frontmatter lines, body lines)."""
    if not lines or lines[0] != "---":
        return [], lines
    for index in range(1, len(lines)):
        if lines[index] == "---":
            return lines[1:index], lines[index + 1 :]
    return lines[1:], []


def strip_quotes(value: str) -> str:
    """Drop one layer of matching quotes, the way the old awk extractor did."""
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def description_source(front: list[str], body: list[str]) -> list[str]:
    """The description text of a skill.

    A block scalar (`description: |`) captures its indented lines. When a new
    frontmatter key ends the block, the capture is final - even when it holds
    nothing, which is why it returns instead of falling through to the body.
    When the block runs to the end of the frontmatter, the body's first
    non-empty line completes the description.
    """
    captured: list[str] = []
    collecting = False
    for line in front:
        if collecting:
            if KEY_RE.match(line):
                # A new key ends the block. Anything captured so far is the
                # description, even when that is nothing.
                return captured
            if line == "" or line[:1] in (" ", "\t"):
                captured.append(line.lstrip())
                continue
            return captured
        if line.startswith("description:"):
            value = line[len("description:") :].lstrip()
            if BLOCK_SCALAR_RE.match(value):
                collecting = True
                continue
            return [strip_quotes(value)]
    if collecting:
        # The block ran to the end of the frontmatter, so the body still
        # follows and its first non-empty line completes the description.
        for line in body:
            if line.strip():
                return [*captured, line]
        return captured
    for line in body:
        if line.strip():
            return [line]
    return []


def compact_description(lines: list[str]) -> str:
    """Collapse a description into one bounded line of trigger text."""
    text = re.sub(r"\s+", " ", " ".join(lines)).strip()
    if len(text) > MAX_DESCRIPTION:
        text = text[: MAX_DESCRIPTION - 3] + "..."
    return text


def yaml_escape(text: str) -> str:
    """Escape a description for a double-quoted YAML scalar."""
    text = "".join(
        character
        for character in text
        if ord(character) >= 0x20 and ord(character) != 0x7F
    )
    return text.replace("\\", "\\\\").replace('"', '\\"')


def frontmatter_block(front: list[str], key: str) -> str:
    """The frontmatter entry for `key`, including a block's indented lines."""
    captured: list[str] = []
    collecting = False
    for line in front:
        if collecting:
            if KEY_RE.match(line):
                break
            if line == "" or line[:1] in (" ", "\t"):
                captured.append(line)
                continue
            break
        if line.startswith(f"{key}:"):
            captured.append(line)
            value = line.split(":", 1)[1].lstrip()
            if value:
                break
            collecting = True
    return "\n".join(captured)


def render_stub(name: str, description: str, blocks: list[str]) -> bytes:
    """The wrapper file content for one skill."""
    lines = [
        "---",
        f"name: nase:workspace:{name}",
        f'description: "{description}"',
        *blocks,
        "---",
        "",
        f"Read `workspace/skills/{name}.md` and follow every step exactly as written.",
        "",
        "$ARGUMENTS",
    ]
    return ("\n".join(lines) + "\n").encode("utf-8")


def write_stub(path: pathlib.Path, data: bytes) -> None:
    """Replace a stub with `data`, keeping the mode the wrapper contract needs."""
    atomic_write(path, data)
    os.chmod(path, STUB_MODE)


def sync(root: pathlib.Path) -> tuple[int, int, int, list[str]]:
    """Sync every workspace skill. Returns (synced, removed, mirrors, messages)."""
    skills_dir = root / "workspace" / "skills"
    commands_dir = root / ".claude" / "commands" / "nase" / "workspace"
    native_dir = root / ".claude" / "skills"
    messages: list[str] = []

    if not skills_dir.is_dir():
        return 0, 0, 0, messages

    commands_dir.mkdir(parents=True, exist_ok=True)
    synced = 0
    for skill_file in sorted(skills_dir.glob("*.md")):
        name = skill_file.stem
        if not NAME_RE.fullmatch(name):
            messages.append(
                f"[session-start] WARNING: skipped workspace skill with unsupported name: {name}"
            )
            continue
        try:
            lines = skill_file.read_text(encoding="utf-8").splitlines()
        except (OSError, UnicodeDecodeError) as error:
            messages.append(
                f"[session-start] WARNING: could not read workspace skill {name}: {error}"
            )
            continue
        front, body = split_frontmatter(lines)
        description = yaml_escape(compact_description(description_source(front, body)))
        blocks = [
            block
            for block in (
                frontmatter_block(front, key) for key in FORWARDED_KEYS
            )
            if block
        ]
        invocation = frontmatter_block(front, INVOCATION_KEY)
        if invocation:
            blocks.append(invocation)
        data = render_stub(name, description, blocks)
        stub = commands_dir / f"{name}.md"
        try:
            current = stub.read_bytes() if stub.exists() else None
        except OSError as error:
            messages.append(
                f"[session-start] WARNING: could not read generated wrapper {stub.name}: {error}"
            )
            continue
        if current == data:
            # Content already matches. Only the mode can still be wrong.
            with contextlib.suppress(OSError):
                os.chmod(stub, STUB_MODE)
            continue
        try:
            write_stub(stub, data)
        except OSError as error:
            messages.append(
                f"[session-start] WARNING: could not write generated wrapper {stub.name}: {error}"
            )
            continue
        synced += 1

    removed = 0
    for stub in sorted(commands_dir.glob("*.md")):
        if not (skills_dir / f"{stub.stem}.md").is_file():
            try:
                stub.unlink()
            except OSError as error:
                messages.append(
                    f"[session-start] WARNING: could not remove orphaned wrapper {stub.name}: {error}"
                )
                continue
            removed += 1

    mirrors = 0
    if native_dir.is_dir():
        for native_file in sorted(native_dir.glob("nase-workspace-*/SKILL.md")):
            try:
                content = native_file.read_text(encoding="utf-8")
            except OSError:
                continue
            if NATIVE_MARKER not in content:
                continue
            try:
                shutil.rmtree(native_file.parent)
            except OSError as error:
                messages.append(
                    f"[session-start] WARNING: could not remove generated native mirror {native_file.parent.name}: {error}"
                )
                continue
            mirrors += 1

    if synced:
        messages.append(
            f"[session-start] synced {synced} skill(s) from workspace/skills/ → /nase:workspace:*"
        )
    if removed:
        messages.append(
            f"[session-start] removed {removed} orphaned skill stub(s) from .claude/commands/nase/workspace/"
        )
    if mirrors:
        messages.append(
            f"[session-start] removed {mirrors} generated native workspace skill mirror(s)"
        )
    return synced, removed, mirrors, messages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        default=str(pathlib.Path(__file__).resolve().parents[2]),
        help="workspace root that holds workspace/skills and .claude/commands",
    )
    args = parser.parse_args()
    root = pathlib.Path(args.root).resolve()
    try:
        synced, removed, mirrors, messages = sync(root)
    except OSError as error:
        print(f"[session-start] WARNING: workspace skill sync failed: {error}")
        return 1
    for message in messages:
        print(message)
    if synced or removed or mirrors:
        return 10
    return 0


if __name__ == "__main__":
    sys.exit(main())
